#!/usr/bin/env python3
"""design/lighthouse/summary.md from the per-page Lighthouse JSON (UPDATE-07, D-142).

The JSON reports embed screenshots and are large, so they stay local (gitignored); this table is what is kept.
scripts/lighthouse.sh calls it after each run. Stale pages (no longer in the site) are skipped.
"""
import json
from pathlib import Path

SITE_PAGES = {"home", "surec", "kurallar", "rapor", "formlar", "sss", "sonuclar", "iletisim", "teslim"}
rows = []
for f in sorted(Path("design/lighthouse").glob("*.json")):
    name = f.stem
    if name.removeprefix("en-").removeprefix("prod-") not in SITE_PAGES and name not in ("en", "prod-en"):
        continue
    d = json.loads(f.read_text(encoding="utf-8"))
    c, a = d["categories"], d["audits"]
    s = lambda k: round(c[k]["score"] * 100) if k in c and c[k]["score"] is not None else "–"
    rows.append(f"| {name} | {s('performance')} | {s('accessibility')} | {s('best-practices')} | {s('seo')} | "
                f"{a['largest-contentful-paint']['displayValue']} | {a['cumulative-layout-shift']['displayValue']} | {d.get('fetchTime', '')[:10]} | {d.get('lighthouseVersion', '')} |")
out = ["# Lighthouse (mobile, median of 3 runs)", "",
       "Generated by `scripts/lighthouse.sh` (production-like build, Apps Script blocked). The full JSON reports are local only.", "",
       "| Page | Performance | Accessibility | Best practices | SEO | LCP | CLS | Measured | Lighthouse |", "|---|---|---|---|---|---|---|---|---|", *rows, ""]
Path("design/lighthouse/summary.md").write_text("\n".join(out), encoding="utf-8")
print(f"lighthouse summary: {len(rows)} pages")
