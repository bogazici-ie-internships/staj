// DESIGN.md → tokens.json (W3C DTCG, via the pinned @google/design.md CLI) → src/styles/tokens.css
//
//   npm run tokens          regenerate both files (committed)
//   npm run tokens:check    CI: fail if either file is stale
//
// DESIGN.md is the source of truth and is never edited by this script. The
// design.md exporter (format "alpha") carries the colours; the non-colour
// scales it does not export yet (radius, borders, shadow, motion) are read from
// the same front matter here. Colours a theme does not define in DESIGN.md are
// derived in DERIVED below and listed in design/DECISIONS.md.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import YAML from "yaml";

const check = process.argv.includes("--check");
const md = readFileSync("DESIGN.md", "utf8");
const front = YAML.parse(md.split(/^---$/m)[1]);

const lint = JSON.parse(execFileSync("npx", ["--no-install", "design.md", "lint", "DESIGN.md"], { encoding: "utf8" }));
const errors = (lint.findings || []).filter((f) => f.severity === "error");
if (errors.length) {
  console.error("DESIGN.md lint errors:\n" + errors.map((e) => `  ${e.path}: ${e.message}`).join("\n"));
  process.exit(1);
}
const dtcgText = execFileSync("npx", ["--no-install", "design.md", "export", "DESIGN.md", "--format", "dtcg"], { encoding: "utf8" });
const dtcg = JSON.parse(dtcgText);

// "light.paper" → { light: { paper: "#f6f4ee" } } — hex as documented, alpha kept.
const themes = { light: {}, dark: {} };
for (const [key, tok] of Object.entries(dtcg.color || {})) {
  if (key.startsWith("$")) continue;
  const [theme, name] = key.split(".");
  // Prefer the value as written in DESIGN.md (keeps rgba() readable).
  themes[theme][name] = front.colors?.[theme]?.[name] ?? tok.$value.hex;
}

// Pairs DESIGN.md leaves to the mockups (reference/Main.dc.html) — see DECISIONS.md D-03.
const DERIVED = {
  light: { "rule-strong": "var(--ink)", "accent-text": "var(--primary)", "on-signal": "#FFFFFF",
           "hatch": "var(--primary)", "live": "#1F7A4D", "focus": "var(--ink)", "scrim": "rgb(14 23 38 / 0.45)", "contour": "rgb(14 23 38 / 0.07)",
           // hero ground (B12, D-51): transparent in light so the paper grain shows through
           "hero-top": "transparent", "hero-bottom": "transparent",
           // full-bleed bands (UPDATE-02 B3, D-42): navy band and ink band
           "band-bg": "#17457F", "band-ink": "#F6F4EE", "band-ink-2": "#D5DDEA", "band-muted": "#B9C6DA",
           "band-accent": "#7CC4FF", "band-teal": "#4FC3BF", "band-rule": "rgb(246 244 238 / 0.22)",
           "inkband-bg": "#0E1726", "inkband-ink": "#F6F4EE", "inkband-ink-2": "#C3CCDD", "inkband-accent": "#7CC4FF", "inkband-rule": "rgb(246 244 238 / 0.2)" },
  dark:  { "primary-tint": "#16264A", "on-signal": "#0B1020", "hatch": "#7CC4FF", "live": "#4FC08A",
           "focus": "#7CC4FF", "scrim": "rgb(0 0 0 / 0.6)", "contour": "rgb(124 196 255 / 0.10)",
           "hero-top": "#0B1020", "hero-bottom": "#0E1530",
           "band-bg": "#13284A", "band-ink": "#E8ECF4", "band-ink-2": "#C3CCDD", "band-muted": "#B9C6DA",
           "band-accent": "#7CC4FF", "band-teal": "#4FC3BF", "band-rule": "rgb(232 236 244 / 0.18)",
           "inkband-bg": "#E8ECF4", "inkband-ink": "#0B1020", "inkband-ink-2": "#3D4A5C", "inkband-accent": "#17457F", "inkband-rule": "rgb(11 16 32 / 0.2)" },
};
for (const t of ["light", "dark"]) {
  for (const [k, v] of Object.entries(DERIVED[t])) if (!(k in themes[t])) themes[t][k] = v;
}
const names = [...new Set([...Object.keys(themes.light), ...Object.keys(themes.dark)])];
for (const n of names) for (const t of ["light", "dark"]) {
  if (!(n in themes[t])) throw new Error(`token ${n} missing in ${t} theme`);
}

// Utopia fluid type scale: 360→1440 px, 17→19 px base, ratio 1.2→1.333.
function fluid(minPx, maxPx, minVw = 360, maxVw = 1440) {
  const slope = (maxPx - minPx) / (maxVw - minVw);
  const intercept = minPx - slope * minVw;
  const r = (n) => +n.toFixed(4);
  return `clamp(${r(minPx / 16)}rem, ${r(intercept / 16)}rem + ${r(slope * 100)}vw, ${r(maxPx / 16)}rem)`;
}
const steps = {};
for (let s = 0; s <= 5; s++) steps[s] = fluid(17 * 1.2 ** s, 19 * 1.333 ** s);

const block = (vars) => names.map((n) => `  --${n}: ${vars[n]};`).join("\n");
const css = `/* GENERATED by scripts/tokens.mjs from DESIGN.md — do not edit. */
:root {
  color-scheme: light;
${block(themes.light)}

  /* type (Utopia 360→1440, 17→19px, 1.2→1.333) */
${Object.entries(steps).map(([s, v]) => `  --step-${s.replace("-", "n")}: ${v};`).join("\n")}
  --text-label: 0.8125rem; /* 13px mono labels */
  --text-small: 0.75rem;  /* 12px chips */
  --display-hero: clamp(64px, 10vw, 156px);
  --display-h2: clamp(36px, 4vw, 56px);

  /* radius / borders / shadow (DESIGN.md: radius, border, shadow) */
  --radius-field: ${front.radius.field};
  --border-hairline: ${front.border.hairline};
  --border-strong: ${front.border.strong};
  --border-double: ${front.border.double};
  --shadow-hard: ${front.shadow.hard};

  /* space: 4px base */
${[4, 8, 12, 16, 24, 32, 48, 64, 96].map((v, i) => `  --space-${i + 1}: ${v / 16}rem;`).join("\n")}
  --gutter: 16px;
  --max-width: 1320px;
  --measure: 66ch;
  --num-col: 2.75rem;   /* REVIEW-01 Note 4: the number column of every numbered item */

  /* motion */
  --ease: ${front.motion.easing};
  --dur-short: 160ms;
  --dur-long: 320ms;
}
@media (min-width: 601px) { :root { --gutter: 32px; } }

/* Gece Vardiyası: follows the OS unless the visitor picked a theme. */
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
    color-scheme: dark;
${block(themes.dark).replace(/^/gm, "  ")}
  }
}
:root[data-theme="dark"] {
  color-scheme: dark;
${block(themes.dark)}
}
`;

const tokensJson = JSON.stringify(dtcg, null, 2) + "\n";
if (check) {
  const stale = [["tokens.json", tokensJson], ["src/styles/tokens.css", css]]
    .filter(([f, c]) => { try { return readFileSync(f, "utf8") !== c; } catch { return true; } });
  if (stale.length) { console.error("stale: " + stale.map((s) => s[0]).join(", ") + " — run npm run tokens"); process.exit(1); }
  console.log("tokens up to date");
} else {
  writeFileSync("tokens.json", tokensJson);
  writeFileSync("src/styles/tokens.css", css);
  console.log(`tokens: ${names.length} colours × 2 themes, ${lint.findings?.length ?? 0} lint warnings (format alpha)`);
}
