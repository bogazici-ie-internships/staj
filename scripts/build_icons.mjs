// Picks the icons the site uses out of lucide-static (ISC) into src/icons/set.ts,
// so only these few paths ship. Re-run after changing NAMES:  node scripts/build_icons.mjs
import { readFileSync, writeFileSync } from "node:fs";
const NAMES = ["file-pen-line", "calendar-clock", "upload", "book-open-text", "stamp", "clipboard-list", "calendar-days",
  "receipt", "shield-check", "check", "circle-alert", "triangle-alert", "mail", "printer", "arrow-right", "arrow-up-right",
  "info", "file-text", "x", "search"];
const nodes = JSON.parse(readFileSync("node_modules/lucide-static/icon-nodes.json", "utf8"));
const out = {};
for (const n of NAMES) {
  if (!nodes[n]) throw new Error(`no icon ${n}`);
  out[n] = nodes[n].map(([tag, attrs]) => `<${tag} ${Object.entries(attrs).filter(([k]) => k !== "key").map(([k, v]) => `${k}="${v}"`).join(" ")}/>`).join("");
}
const v = JSON.parse(readFileSync("node_modules/lucide-static/package.json", "utf8")).version;
writeFileSync("src/icons/set.ts", `// GENERATED by scripts/build_icons.mjs from lucide-static ${v} (ISC, © Lucide Icons and Contributors).\nexport const ICONS = ${JSON.stringify(out, null, 1)} as const;\nexport type IconName = keyof typeof ICONS;\n`);
console.log(`${NAMES.length} icons → src/icons/set.ts`);
// The path data ships inside pages and islands, so the ISC notice ships too.
writeFileSync("public/assets/LICENSE-lucide.txt", readFileSync("node_modules/lucide-static/LICENSE", "utf8"));
