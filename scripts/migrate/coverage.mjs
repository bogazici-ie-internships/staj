// Coverage report (UPDATE-06 Phase 2a): every heading, paragraph, list item, table row,
// admonition/card/tab/question title and abbreviation of the live site (main, all nine
// docs/*.md pairs) must map to new content — or be listed as intentionally omitted with a reason.
//  - Phase 2a pages: src/content/docs/*.yaml blocks carry `src: "<tr>:<line> · <en>:<line>"`.
//  - Phase 1 pages (index, kurallar, teslim): scripts/migrate/phase1-map.yaml maps "<file>:<line>" → new key
//    (or "omitted: <reason>").
// Fails (exit 1) on: an old unit with no mapping; a new docs block whose src cites no old unit;
// a mapped block whose numbers (digits, plus spelled-out numbers before a unit) were lost.
//   node scripts/migrate/coverage.mjs            → design/reviews/coverage-report.md
import { existsSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import YAML from "yaml";
import { collect } from "../copy/collect.mjs";
import { parse, readMain, units } from "./mkdocs.mjs";
import { redactSample } from "../lib/redact-sample.mjs";

// Every phase1-map target must resolve: "omitted: <reason>", "code: <existing file> — <note>", or
// "<file › key>[, <file › key>…][ — note]" where each key is a copy string (or a prefix of some).
const strings = await collect();
const keys = [...strings.keys()];
function resolveTarget(v) {
  if (/^omitted: .+/.test(v)) return { ok: true, refs: [] };
  const [refsPart] = v.split(" — ");
  if (refsPart.startsWith("code: ")) { const f = refsPart.slice(6).trim(); return { ok: existsSync(f), refs: [], why: `no file ${f}` }; }
  const refs = refsPart.split(", ").map((r) => r.trim());
  const bad = refs.filter((r) => !keys.some((k) => k === r || k.startsWith(r + ".")));
  return { ok: !bad.length, refs, why: bad.length ? `unknown key(s): ${bad.join("; ")}` : "" };
}
const textOf = (refs, lang) => refs.flatMap((r) => keys.filter((k) => k === r || k.startsWith(r + ".")).map((k) => strings.get(k)[lang])).join(" ¶ ");

const PAIRS = [["index", "Home"], ["kurallar", "Kurallar"], ["teslim", "Teslim"], ["surec/index", "Süreç"], ["rapor", "Rapor"],
  ["formlar", "Formlar"], ["sss", "SSS"], ["sonuclar", "Sonuçlar"], ["iletisim", "İletişim"]];
const WORDS = { one: 1, two: 2, three: 3, four: 4, five: 5, six: 6, seven: 7, eight: 8, nine: 9, ten: 10, bir: 1, iki: 2, "üç": 3, "dört": 4, "beş": 5, on: 10 };
const UNIT = "(?:iş |working )?(?:gün|hafta|dakika|saat|yarıyıl|sayfa|days?|weeks?|minutes?|hours?|semesters?|pages?|workdays?|MB)";
const nums = (s) => {
  const t = String(s).replace(/\{[^}]+\}|\(link:\w+\)|\(doc:[^)]+\)|\(page:[^)]+\)|\]\([^)]*\)|https?:\S+|[\w.-]+\.(pdf|docx)|GMT\+3|EK-1|\b\d+\.\s/g, " ");
  const out = [...t.matchAll(/\d+/g)].map((m) => m[0]);
  for (const m of t.matchAll(new RegExp(`(?<!\\p{L})(${Object.keys(WORDS).join("|")})\\s+${UNIT}`, "giu"))) out.push(String(WORDS[m[1].toLowerCase()]));
  return out.sort();
};
const lost = (a, b) => { const bb = [...b]; return a.filter((x) => { const i = bb.indexOf(x); if (i < 0) return true; bb.splice(i, 1); return false; }); };

// New side: every src in the docs collection, with the text it carries.
const mapped = new Map(); // "file:line" → [{ key, tr, en }]
const bad = [];
function walk(node, path, page) {
  if (Array.isArray(node)) return node.forEach((v, i) => walk(v, [...path, i], page));
  if (!node || typeof node !== "object") return;
  if (typeof node.src === "string") {
    const text = node.text ?? node.title ?? node.q ?? node.label ?? (node.cells ? { tr: node.cells.map((c) => c.tr).join(" | "), en: node.cells.map((c) => c.en).join(" | ") } : null);
    if (node.src.startsWith("new")) mapped.set(`new:${page}:${path.join(".")}`, [{ key: `${page} › ${path.join(".")}`, ...text, note: node.src }]);
    else for (const ref of node.src.split(" · ")) {
      (mapped.get(ref) ?? mapped.set(ref, []).get(ref)).push({ key: `docs/${page}.yaml › ${path.join(".")}`, tr: text?.tr, en: text?.en, kind: node.kind });
    }
  }
  for (const [k, v] of Object.entries(node)) if (k !== "src") walk(v, [...path, k], page);
}
for (const f of readdirSync("src/content/docs").filter((f) => f.endsWith(".yaml"))) walk(YAML.parse(readFileSync(`src/content/docs/${f}`, "utf8")), [], f.replace(".yaml", ""));
const phase1 = YAML.parse(readFileSync("scripts/migrate/phase1-map.yaml", "utf8")) ?? {};
const mapProblems = [];
for (const [ref, v] of Object.entries(phase1)) {
  const r = resolveTarget(String(v));
  if (!r.ok) mapProblems.push(`phase1-map ${ref}: ${r.why}`);
  (mapped.get(ref) ?? mapped.set(ref, []).get(ref)).push({ key: String(v), phase1: true, tr: r.refs.length ? textOf(r.refs, "tr") : null, en: r.refs.length ? textOf(r.refs, "en") : null });
}

const lines = ["# Coverage report — live site (`main`, docs/) → redesign", "",
  "Generated by `node scripts/migrate/coverage.mjs` (fails on any unmapped unit, any orphan new block, or any lost number).",
  "Units: every heading, paragraph, list item, table row, admonition / card / tab / question title, abbreviation and raw-HTML block of the nine live page pairs. TR and EN were checked to have the same structure (the TR files carry one extra abbreviation); the TR line is listed, the EN line is in the `src` of the new block.", ""];
let total = 0, ok = 0, omitted = 0;
const problems = [...mapProblems];
const seen = new Set();
const html = [];
const esc = (x) => String(x ?? "").replace(/[&<>]/g, (c) => ({ "&": "&amp;", "<": "&lt;", ">": "&gt;" })[c]);
for (const [file, name] of PAIRS) {
  const tr = units(parse(readMain(`docs/${file}.md`), `${file}.md`));
  const en = units(parse(readMain(`docs/${file}.en.md`), `${file}.en.md`));
  lines.push(`## ${name} — \`docs/${file}.md\``, "", "| Line | Unit | Old (TR, start) | New | Numbers |", "|---|---|---|---|---|");
  html.push(`<h2>${esc(name)} — docs/${esc(file)}.md</h2><table><thead><tr><th>Line</th><th>Unit</th><th>Old TR</th><th>New TR</th><th>Old EN</th><th>New EN</th><th>Key</th></tr></thead><tbody>`);
  tr.forEach((u, i) => {
    total++;
    const ref = `${file}.md:${u.line}`;
    seen.add(ref); if (en[i]) seen.add(`${file}.en.md:${en[i].line}`);
    const hits = mapped.get(ref) ?? [];
    const short = String(u.text).replace(/\s+/g, " ").replace(/\|/g, "\\|").slice(0, 70);
    if (!hits.length) { problems.push(`unmapped ${ref} (${u.kind}) ${short}`); lines.push(`| ${u.line} | ${u.kind} | ${short} | **✘ unmapped** | |`); html.push(`<tr class="bad"><td>${u.line}</td><td>${u.kind}</td><td>${esc(u.text)}</td><td>✘ unmapped</td><td>${esc(en[i]?.text)}</td><td></td><td></td></tr>`); return; }
    const h = hits[0];
    let numCol = "";
    if (!h.phase1 && h.tr != null) {
      const l1 = lost(nums(u.text), nums(hits.map((x) => x.tr).join(" ")));
      const l2 = en[i] ? lost(nums(en[i].text), nums(hits.map((x) => x.en).join(" "))) : [];
      if (l1.length || l2.length) { problems.push(`numbers lost at ${ref}: TR [${l1}] EN [${l2}]`); numCol = `✘ lost TR [${l1}] EN [${l2}]`; } else numCol = nums(u.text).length ? "✓" : "";
    }
    if (/^omitted/.test(h.key)) omitted++; else ok++;
    lines.push(`| ${u.line} | ${u.kind} | ${short} | ${hits.map((x) => `\`${x.key.replace(/\|/g, "\\|")}\``).join("<br>")} | ${numCol} |`);
    const newTr = hits.map((x) => x.tr).filter((x) => x != null).join(" ¶ "), newEn = hits.map((x) => x.en).filter((x) => x != null).join(" ¶ ");
    html.push(`<tr${/^omitted/.test(h.key) ? ' class="omit"' : ""}><td>${u.line}</td><td>${u.kind}</td><td>${esc(u.text)}</td><td>${esc(newTr) || "—"}</td><td>${esc(en[i]?.text)}</td><td>${esc(newEn) || "—"}</td><td><code>${hits.map((x) => esc(x.key)).join("<br>")}</code>${numCol ? ` ${esc(numCol)}` : ""}</td></tr>`);
  });
  lines.push("");
  html.push("</tbody></table>");
}
// Orphans: new blocks that cite a line that is not a unit (typo) — "new" blocks are listed for review.
const added = [];
for (const [ref, hits] of mapped) {
  if (ref.startsWith("new:")) { added.push(`| \`${hits[0].key}\` | ${hits[0].note} | ${(hits[0].tr ?? "").slice(0, 80).replace(/\|/g, "\\|")} |`); continue; }
  if (!seen.has(ref)) problems.push(`orphan: ${hits.map((h) => h.key).join(", ")} cites ${ref}, which is not a unit`);
}
lines.splice(4, 0, `**${total} units: ${ok} mapped, ${omitted} intentionally omitted (reason given), ${total - ok - omitted} unmapped.** Problems: ${problems.length}.`, "");
if (added.length) lines.push("## New text (not on the live site)", "", "| Key | Why | TR |", "|---|---|---|", ...added, "");
if (problems.length) lines.push("## Problems", "", ...problems.map((p) => `- ${p}`), "");
writeFileSync("design/reviews/coverage-report.md", redactSample(lines.join("\n")));
writeFileSync("design/reviews/coverage-report.html", redactSample(`<!doctype html><meta charset="utf-8"><meta name="viewport" content="width=device-width,initial-scale=1"><title>Coverage — old vs new</title>
<style>body{font:14px/1.45 system-ui;margin:24px;background:#f6f4ee;color:#111}table{border-collapse:collapse;width:100%;margin-bottom:32px;background:#fff}th,td{border:1px solid #ccc;padding:6px 8px;vertical-align:top;text-align:left}th{background:#e9e6dc;position:sticky;top:0}td:nth-child(3),td:nth-child(5){color:#555}tr.omit td{background:#f3f0e6;color:#666}tr.bad td{background:#fde2dd}code{font-size:12px}h2{margin-top:40px}</style>
<h1>Coverage — every unit of the live site, old text next to new text</h1>
<p>Generated by <code>node scripts/migrate/coverage.mjs</code>. Old = main docs (TR line given; EN paired by structure). New = the redesign string(s) the unit maps to (¶ separates several). Grey rows were omitted with the reason in the Key column.</p>
${html.join("\n")}`));
console.log(`coverage: ${total} units, ${ok} mapped, ${omitted} omitted, ${problems.length} problem(s)`);
if (problems.length) { console.log(problems.slice(0, 40).join("\n")); process.exit(1); }
